async page => {
  const base=page.url();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:900});
  await page.goto(base);
  await page.clock.install();
  await page.getByRole('button',{name:'Focus timer',exact:true}).click();
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByRole('button',{name:'Start / resume',exact:true}).click();
  await page.getByRole('button',{name:'Close menu',exact:true}).click();
  const timerBefore=await page.evaluate(async()=>JSON.stringify((await import('/src/main.js')).data.pomodoro));
  const timerLabelBefore=await page.locator('.rail-timer-label').textContent();
  await page.locator('.rail [data-action="mindfulness-open"]').click();
  const dialog=page.getByRole('dialog',{name:'Mindful breathing'});
  if(!await dialog.isVisible())throw Error('Mindfulness dialog did not open');
  if(!await page.locator('.app-shell').evaluate(el=>el.inert))throw Error('Workspace is interactive behind mindfulness dialog');
  await page.getByText('Time & pace',{exact:true}).click();
  await page.getByLabel('Mindfulness duration').selectOption('3');
  await page.getByLabel('Breathing pace').selectOption('8');
  for(const [width,height] of [[320,568],[390,667],[844,390],[1440,900]]){await page.setViewportSize({width,height});if(await page.locator('.mindfulness-card').evaluate(el=>el.scrollHeight>el.clientHeight+1))throw Error('Expanded breathing settings overflow '+width+'x'+height);}
  await page.getByRole('button',{name:'Begin',exact:true}).click();
  if(await page.locator('#breath-phase').textContent()!=='Breathe in')throw Error('Exercise did not begin with inhale');
  if(await page.locator('.breath-orb').evaluate(el=>getComputedStyle(el).animationName)!=='mindful-breath')throw Error('Breathing animation did not start');
  await page.clock.fastForward(4000);
  if(await page.locator('#breath-phase').textContent()!=='Breathe out')throw Error('Breathing phase did not advance');
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  const remaining=await page.locator('#mindfulness-remaining').textContent();
  await page.clock.fastForward(10000);
  if(await page.locator('#mindfulness-remaining').textContent()!==remaining)throw Error('Pause did not stop mindfulness session');
  await page.getByRole('button',{name:'Resume',exact:true}).click();
  await page.clock.fastForward(176000);
  if(!await page.getByText('A moment, taken').isVisible())throw Error('Mindfulness session did not complete');
  const timerAfter=await page.evaluate(async()=>JSON.stringify((await import('/src/main.js')).data.pomodoro));
  if(timerAfter!==timerBefore)throw Error('Mindfulness changed Pomodoro state');
  if(await page.locator('.rail-timer-label').textContent()===timerLabelBefore)throw Error('Pomodoro stopped while mindfulness was open');
  await page.screenshot({path:'/tmp/patchwork-mindfulness-desktop.png'});
  await page.keyboard.press('Escape');
  if(await dialog.count())throw Error('Escape did not close mindfulness dialog');
  if(!await page.locator('.rail [data-action="mindfulness-open"]').evaluate(el=>el===document.activeElement))throw Error('Focus did not return to mindfulness icon');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.mobile-topbar [data-action="mindfulness-open"]').click();
  await page.getByText('Time & pace',{exact:true}).click();
  if(await page.getByLabel('Mindfulness duration').inputValue()!=='3')throw Error('Duration preference was lost');
  if(await page.getByLabel('Breathing pace').inputValue()!=='8')throw Error('Pace preference was lost');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'Begin',exact:true}).click();
  if(await page.locator('.breath-orb').evaluate(el=>getComputedStyle(el).animationName)!=='none')throw Error('Reduced motion still animates breathing circle');
  await page.screenshot({path:'/tmp/patchwork-mindfulness-mobile.png'});
  return 'PASS independent mindfulness control, phase timing, pause/resume, completion, focus return, saved settings, mobile and reduced motion';
}
