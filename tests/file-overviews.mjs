import assert from 'node:assert/strict';
import { generateFileOverviews, skipFileOverview } from '../file-overviews.mjs';
import { createAgentGuideService } from '../agent-guide-service.mjs';

assert(skipFileOverview('nested/package-lock.json'));
assert(skipFileOverview('pnpm-lock.yaml'));
assert(!skipFileOverview('src/package.json'));
const files=Array.from({length:17},(_,i)=>({path:`src/file-${i}.js`,id:`id-${i}`,status:'modified',lines:[['added','1',`export const value = ${i};`]]}));
files.push({path:'package-lock.json',id:'lock',status:'modified',lines:[]});
const snapshot={snapshotId:'overview-snapshot',repoId:'repo',scope:'all',files};
const repository={snapshot,manifest:files.map(file=>({path:file.path,fileId:file.id,changed:true,available:true})),read:path=>({source:`source for ${path}`,version:'v'})};
const gates=[],progress=[];
const batchPaths=prompt=>JSON.parse(prompt.slice(prompt.lastIndexOf('\n[')+1)).map(file=>file.path);
const ai={generate(prompt,options){return new Promise(resolve=>gates.push({prompt,options,resolve}));}};
const pending=generateFileOverviews(repository,ai,{model:'luna',effort:'xhigh',onProgress:value=>progress.push(value)});
await new Promise(setImmediate);
assert.equal(gates.length,3,'Three batches should start without waiting for one another');
assert.equal(new Set(gates.map(gate=>gate.options.parallelKey)).size,3);
assert.equal(progress[0].completed,1,'Lockfile is skipped immediately');
assert.equal(progress[0].overviewStatus['package-lock.json'],'skipped');
const reply=gate=>gate.resolve({status:200,body:{text:JSON.stringify({files:batchPaths(gate.prompt).map(path=>({path,summary:`Specific change in ${path}.`}))})}});
reply(gates[1]);await new Promise(setImmediate);
assert.equal(progress.at(-1).completed,9,'A completed batch is published before the others finish');
assert.equal(progress.at(-1).overviewStatus['src/file-8.js'],'ready');
assert.equal(progress.at(-1).overviewStatus['src/file-0.js'],undefined);
reply(gates[0]);reply(gates[2]);
const result=await pending;
assert.equal(Object.keys(result.fileOverviews).length,17);
assert.equal(result.overviewStatus['package-lock.json'],'skipped');

const calls=[];
const service=createAgentGuideService({getRepository:()=>repository},{async generate(prompt,options){calls.push({prompt,options});if(options.parallelKey)return {status:200,body:{text:JSON.stringify({files:batchPaths(prompt).map(path=>({path,summary:`Specific change in ${path}.`}))})}};assert.match(prompt,/Specific change in src\/file-0\.js/);return {status:200,body:{text:JSON.stringify({title:'Review',summary:'Related changes',assumptions:[],steps:[{title:'Read related files',explanation:'Each file changes its value.',files:files.map(file=>file.path),citations:[]}]})}};}});
const started=service.start({requestId:'overview-service-0001',snapshotId:snapshot.snapshotId,model:'luna',effort:'xhigh'});
assert.equal(started.status,'running');
assert.equal((await service.runs.wait(started.id)).status,'completed');
assert.equal(service.runs.get(started.id).progress.ready,17);
assert.equal(service.runs.get(started.id).progress.fileOverviews,undefined,'Progress must stay small; summaries are read from the conversation');
assert.equal(calls.filter(call=>call.options.parallelKey).length,3);
assert.equal(calls.filter(call=>!call.options.parallelKey).length,1);
assert.equal(service.conversation(started.id).fileOverviews['src/file-0.js'],'Specific change in src/file-0.js.');
assert.equal(service.conversation(started.id).overviewStatus['package-lock.json'],'skipped');
assert.equal(service.conversation(started.id).guide.fileOverviews['src/file-0.js'],'Specific change in src/file-0.js.');
console.log('File overviews passed: bounded parallel batches, early progress, lockfile skip, per-file summaries and walkthrough context.');
