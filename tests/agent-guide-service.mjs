import assert from 'node:assert/strict';
import { createAgentGuideService, repositoryGuideTimeoutMs } from '../agent-guide-service.mjs';
import { SINGLE_FILE_REPOSITORY_GUIDE_SCHEMA } from '../agent-plan.mjs';
const batchPaths=prompt=>JSON.parse(prompt.slice(prompt.lastIndexOf('\n[')+1)).map(file=>file.path);
const overviewReply=prompt=>({status:200,body:{text:JSON.stringify({files:batchPaths(prompt).map(path=>({path,summary:`${path} changes this behavior.`}))})}});
const files = ['a.js','b.js'].map((path,i)=>({path,id:String(i),lines:[['added','1','new code']]}));
const snapshot = { snapshotId:'s',repoId:'r',scope:'all',files };
const sources = new Map([['a.js','new code'],['b.js','new code'],['caller.js','callA();']]);
const repository = { snapshot, manifest:[...sources].map(([path])=>({path,changed:path!=='caller.js',available:true,fileId:files.find(f=>f.path===path)?.id||null})), read(path){if(!sources.has(path))throw Error('Unknown path');return {source:sources.get(path),version:'v'};} };
const snapshots = {getRepository(id){assert.equal(id,'s');return repository;}};
const plan = {title:'Overview',summary:'Two related changes',assumptions:[],fileOverviews:files.map(file=>({path:file.path,summary:`${file.path} changes this behavior.`})),steps:files.map(file=>({title:file.path,explanation:'Explain this change',files:[file.path],citations:[{path:file.path,side:'new',startLine:1,endLine:1}]}))};
const calls=[];
const ai={async generate(prompt,options){calls.push({prompt,options});if(options.parallelKey)return overviewReply(prompt);options.onThread('thread-'+options.sessionKey);options.repositoryTools.call('review_read',{path:'caller.js'});options.onActivity({tool:'review_read',path:'caller.js'});options.onDelta('Thinking');return {status:200,body:{text:options.jsonSchema?JSON.stringify(plan):'Follow-up answer'}};}};
const service=createAgentGuideService(snapshots,ai);
assert.equal(repositoryGuideTimeoutMs(1),5*60_000);
assert.equal(repositoryGuideTimeoutMs(90),45*60_000);
assert.equal(repositoryGuideTimeoutMs(1000),60*60_000);
const main='main-conversation-01';
service.start({requestId:main,snapshotId:'s',selectedPath:'a.js'});
const completed=await service.runs.wait(main);assert.equal(completed.status,'completed');assert.equal(completed.result.guide.totalChangedFiles,2);
assert.equal(service.conversation(main).guide.fileOverviews['a.js'],'a.js changes this behavior.');
assert.equal(calls[1].options.turnTimeoutMs,5*60_000);
service.start({requestId:main,snapshotId:'s',selectedPath:'a.js'});assert.equal(calls.length,2);
service.selectStep(main,1);
const child='child-conversation-01';
service.question({requestId:child,conversationId:main,question:'Explain this more',step:0,branch:true});
await service.runs.wait(child);
assert.equal(calls[2].options.turnTimeoutMs,undefined);
assert.equal(service.conversation(main).step,1);
assert.equal(service.conversation(main).messages.length,0);
assert.equal(service.conversation(child).step,0);
assert.equal(service.conversation(child).parentId,main);
assert.equal(calls[2].options.forkSessionKey,'repository:s:'+main);
assert.equal(service.conversation(child).messages.length,2);
service.question({requestId:'followup-request-01',conversationId:child,question:'An example?'});
await service.runs.wait('followup-request-01');
assert.equal(calls[3].options.forkSessionKey,undefined);
assert.equal(calls[3].options.sessionKey,'repository:s:'+child);
assert.equal(service.conversation(child).messages.length,4);
assert(!('threadId' in service.conversation(child)));
assert.throws(()=>service.selectStep(main,10),error=>error.status===400);
assert.throws(()=>service.question({requestId:'bad-question-00001',conversationId:main,question:''}),error=>error.status===400);
assert.throws(()=>service.start({requestId:main,snapshotId:'s',selectedPath:'b.js'}),error=>error.status===409);
assert.equal(service.list('s').length,2);
let repairCalls=0;
const repairing=createAgentGuideService(snapshots,{async generate(prompt,options){
 if(options.parallelKey)return overviewReply(prompt);
 repairCalls++;options.onThread('repair-thread');
 if(repairCalls===1){const invalid=structuredClone(plan);invalid.steps[1].files.push('b.js');return {status:200,body:{text:JSON.stringify(invalid)}};}
 assert.match(prompt,/appears more than once/);
 return {status:200,body:{text:JSON.stringify(plan)}};
}});
repairing.start({requestId:'repair-request-0001',snapshotId:'s'});
assert.equal((await repairing.runs.wait('repair-request-0001')).status,'completed');assert.equal(repairCalls,2);
const manyFiles=Array.from({length:90},(_,i)=>({path:`file-${i}.js`,id:`many-${i}`,lines:[['added','1',`value${i}`]]}));
const manyRepository={snapshot:{...snapshot,files:manyFiles},manifest:manyFiles.map(file=>({path:file.path,fileId:file.id,changed:true,available:true})),read:()=>({source:'value',version:'v'})};
let largeCalls=0;
const manyService=createAgentGuideService({getRepository:()=>manyRepository},{async generate(prompt,options){if(options.parallelKey)return overviewReply(prompt);largeCalls++;assert.match(prompt,/file-0.js changes this behavior/);return {status:200,body:{text:JSON.stringify({title:'Large change',summary:'Related files',assumptions:[],steps:[{title:'Review the change',explanation:'These files implement the same behavior.',files:manyFiles.map(file=>file.path),citations:[]}]})}};}});
manyService.start({requestId:'large-guide-request-01',snapshotId:'s'});
assert.equal((await manyService.runs.wait('large-guide-request-01')).status,'completed');
assert.equal(largeCalls,1,'A 90-file guide must not retry because individual overviews are missing');
assert.equal(Object.keys(manyService.conversation('large-guide-request-01').guide.fileOverviews).length,90);
const oneFile={...snapshot,files:[files[0]]};
const oneRepository={...repository,snapshot:oneFile};
const onePlan={title:'One change',summary:'The file changes behavior.',assumptions:[],fileOverviews:[{path:'a.js',summary:'a.js changes this behavior.'}],steps:[{title:'Read a.js',explanation:'The new line changes behavior.',files:['a.js'],citations:[{path:'a.js',side:'new',startLine:1,endLine:1}]}]};
const oneCalls=[];
const oneService=createAgentGuideService({getRepository:()=>oneRepository},{async generate(prompt,options){oneCalls.push({prompt,options});return {status:200,body:{text:JSON.stringify(onePlan)}};}});
oneService.start({requestId:'one-file-request-01',snapshotId:'s'});
assert.equal((await oneService.runs.wait('one-file-request-01')).status,'completed');
assert.equal(oneCalls.length,1,'A single changed file should need one AI call for its overview and plan.');
assert.equal(oneCalls[0].options.jsonSchema,SINGLE_FILE_REPOSITORY_GUIDE_SCHEMA);
assert.equal(oneService.conversation('one-file-request-01').guide.fileOverviews['a.js'],'a.js changes this behavior.');
const deepCalls=[];
const deepService=createAgentGuideService(snapshots,{async generate(prompt,options){deepCalls.push({prompt,options});return {status:200,body:{text:`Answer ${deepCalls.length}`}};}});
const deepId='deep-review-request-01';
deepService.startDeep({requestId:deepId,snapshotId:'s'});
deepService.deepQuestion({requestId:'deep-question-000001',conversationId:deepId,question:'Why this line?',index:0,group:0});
assert.equal((await deepService.runs.wait('deep-question-000001')).status,'completed');
deepService.deepQuestion({requestId:'deep-question-000002',conversationId:deepId,question:'And the caller?',index:0,group:0});
await deepService.runs.wait('deep-question-000002');
assert.match(deepCalls[0].prompt,/a\.js, new lines 1-1[\s\S]*Why this line\?/);
assert(deepCalls[0].options.repositoryTools,'Deep follow-ups can explore the captured repository.');
assert.deepEqual(deepCalls[1].options.transcript,[{role:'user',text:'Why this line?'},{role:'assistant',text:'Answer 1'}]);
assert.deepEqual(deepService.conversation(deepId).messages.map(m=>[m.role,m.index]),[['user',0],['assistant',0],['user',0],['assistant',0]]);
assert.throws(()=>deepService.deepQuestion({requestId:'deep-question-000003',conversationId:deepId,question:'',index:0}),error=>error.status===400);
assert.throws(()=>deepService.deepQuestion({requestId:'deep-question-000004',conversationId:deepId,question:'Hi',index:99}),error=>error.status===400);
let lessonPrompts=[];
const lessonService=createAgentGuideService(snapshots,{async generate(prompt,options){
 if(options.parallelKey==='file-overview-0'||options.parallelKey?.startsWith('file-overview'))return overviewReply(prompt);
 if(options.jsonSchema===SINGLE_FILE_REPOSITORY_GUIDE_SCHEMA||options.jsonSchema?.properties?.steps)return {status:200,body:{text:JSON.stringify(plan)}};
 if(!options.jsonSchema)return {status:200,body:{text:'Answered while the lesson prepared.'}};
 lessonPrompts.push({prompt,options});return {status:200,body:{text:JSON.stringify({title:'Broken',segments:[],reviewPointers:[]})}};
}});
lessonService.start({requestId:'lesson-main-request-01',snapshotId:'s',selectedPath:'a.js'});
assert.equal((await lessonService.runs.wait('lesson-main-request-01')).status,'completed');
lessonService.lesson({requestId:'lesson-prefetch-req-01',conversationId:'lesson-main-request-01',step:1,prefetch:true});
lessonService.question({requestId:'lesson-question-req-01',conversationId:'lesson-main-request-01',question:'While that prepares?',step:0});
assert.equal((await lessonService.runs.wait('lesson-prefetch-req-01')).status,'failed');
assert.equal(lessonPrompts[0].options.parallelKey,'prefetch');
assert.equal((await lessonService.runs.wait('lesson-question-req-01')).status,'completed','A question must run while a lesson prefetches.');
assert.match(lessonPrompts[1].prompt,/Previous answer JSON:\n\{"title":"Broken"/,'A lesson retry must repair the rejected answer instead of starting over.');
console.log('Agent guide service passed: tool-backed generation, validated plan, duplicate prevention, branched context, main-step preservation, continuing follow-ups and deep review questions.');
